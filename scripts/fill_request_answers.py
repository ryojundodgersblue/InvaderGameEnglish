def fill(ws, answers, label):
    count = 0
    for row in ws.iter_rows(min_row=4):
        no = row[0].value
        if no not in answers:
            continue
        answer, status, done = answers[no]
        if row[4].value:  # 既に回答がある行は触らない
            continue
        row[4].value = answer
        if status:
            row[5].value = status
        if done:
            row[6].value = done
        count += 1
    print(f'{label}: {count}件の回答を記入')


def main():
    wb = openpyxl.load_workbook(REQ_XLSX)
    fill(wb['機能・仕様要望'], FEATURE_ANSWERS, '機能・仕様要望')
    fill(wb['不具合・改善報告'], BUG_ANSWERS, '不具合・改善報告')
    wb.save(REQ_XLSX)
    print('OK: 要望書の回答記入完了')
    return 0


